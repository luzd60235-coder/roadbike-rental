export function appendOptionIfMissing(options, value) {
  const normalizedValue = typeof value === 'string' ? value.trim() : value

  if (normalizedValue == null || normalizedValue === '') {
    return options
  }

  return options.some((item) => item.value === normalizedValue)
    ? options
    : [...options, { label: normalizedValue, value: normalizedValue }]
}

export function normalizeBikeFrameSize(value) {
  return value ? String(value).trim().toUpperCase() : ''
}

export function normalizeBikeColor(value) {
  const text = value ? String(value).trim() : ''

  if (!text) {
    return ''
  }

  return COLOR_ALIAS_MAP[text.toLowerCase()] || text
}
